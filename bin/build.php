<?php
/**
 * Build step (plain PHP, no Node): run after editing data/pages or
 * data/redirects.
 *
 *   php bin/build.php
 *
 * 1. Writes a two-line index.php stub into the directory of every page and
 *    directory-style redirect, so clean URLs work on any cPanel host even
 *    without mod_rewrite.
 * 2. Writes stubs for legacy *.php redirects at the web root.
 * 3. Removes stubs that are no longer referenced (only files carrying the
 *    generated marker are ever deleted).
 * 4. Regenerates sitemap.xml from indexable pages and the SVG icon sprite.
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

require dirname(__DIR__) . '/includes/bootstrap.php';

const MARKER = 'Generated by bin/build.php';
const PROTECTED_DIRS = ['assets', 'bin', 'cms', 'config', 'data', 'database', 'docs', 'includes', 'seo', 'storage', '.git'];

$written = 0;
$wanted = [];

$stubFor = static function (string $path): string {
    $depth = substr_count(trim($path, '/'), '/') + ($path === '/' ? 0 : 1);
    $boot = $depth === 0 ? "__DIR__ . '/includes/bootstrap.php'" : "dirname(__DIR__, {$depth}) . '/includes/bootstrap.php'";
    return "<?php\n// " . MARKER . " (content lives in data/pages). Do not edit.\nrequire {$boot};\nacad_serve(__DIR__);\n";
};

$targets = [];
foreach (acad_pages() as $path => $page) {
    if (empty($page['virtual'])) {
        $targets[$path] = 'page';
    }
}
foreach (acad_redirects() as $from => $to) {
    if (isset($targets[$from])) {
        fwrite(STDERR, "Conflict: {$from} is both a page and a redirect\n");
        exit(1);
    }
    if (!acad_page($to)) {
        fwrite(STDERR, "Redirect target missing: {$from} -> {$to}\n");
        exit(1);
    }
    $targets[$from] = 'redirect';
}

foreach ($targets as $path => $kind) {
    if (str_ends_with($path, '.php')) {
        $file = ACAD_ROOT . $path;
        $code = "<?php\n// " . MARKER . ". Legacy URL redirect. Do not edit.\nrequire __DIR__ . '/includes/bootstrap.php';\nacad_dispatch('{$path}');\n";
    } else {
        $first = explode('/', trim($path, '/'))[0];
        if (in_array($first, PROTECTED_DIRS, true)) {
            fwrite(STDERR, "Refusing to write into protected directory for {$path}\n");
            exit(1);
        }
        $dir = rtrim(ACAD_ROOT . $path, '/');
        if (!is_dir($dir)) {
            mkdir($dir, 0755, true);
        }
        $file = $dir . '/index.php';
        $code = $stubFor($path);
    }
    $wanted[realpath(dirname($file)) . '/' . basename($file)] = true;
    if (is_file($file) && !str_contains((string) file_get_contents($file), MARKER)) {
        fwrite(STDERR, "Skipping hand-written file {$file}\n");
        continue;
    }
    if (!is_file($file) || file_get_contents($file) !== $code) {
        file_put_contents($file, $code);
        $written++;
    }
}

// Remove orphaned generated stubs.
$removed = 0;
$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator(ACAD_ROOT, FilesystemIterator::SKIP_DOTS));
foreach ($it as $f) {
    $rel = substr($f->getPathname(), strlen(ACAD_ROOT) + 1);
    if (in_array(explode('/', $rel)[0], PROTECTED_DIRS, true) || $f->getExtension() !== 'php') {
        continue;
    }
    if (!isset($wanted[$f->getPathname()]) && str_contains((string) file_get_contents($f->getPathname()), MARKER)) {
        unlink($f->getPathname());
        $removed++;
        $dir = dirname($f->getPathname());
        while ($dir !== ACAD_ROOT && is_dir($dir) && count(scandir($dir)) === 2) {
            rmdir($dir);
            $dir = dirname($dir);
        }
    }
}

// Icon sprite.
file_put_contents(ACAD_ROOT . '/assets/img/icons.svg', acad_icon_sprite());

// sitemap.xml
$xml = '<?xml version="1.0" encoding="UTF-8"?>' . "\n" . '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
$count = 0;
foreach (acad_public_pages() as $path => $page) {
    if (!empty($page['virtual']) || $page['template'] === 'search') {
        continue;
    }
    $lastmod = date('Y-m-d', (int) filemtime(ACAD_ROOT . '/data/pages/' . $page['source']));
    $xml .= '  <url><loc>' . htmlspecialchars(acad_url($path), ENT_XML1) . '</loc><lastmod>' . $lastmod . "</lastmod></url>\n";
    $count++;
}
$xml .= "</urlset>\n";
file_put_contents(ACAD_ROOT . '/sitemap.xml', $xml);

// docs/URL_INVENTORY.md
$md = "# URL inventory\n\nGenerated by `php bin/build.php`. Do not edit by hand.\n\n## Pages\n\n| # | Path | Title | Indexed |\n|---:|---|---|---|\n";
$i = 0;
foreach (acad_pages() as $path => $page) {
    $md .= '| ' . ++$i . ' | `' . $path . '` | ' . str_replace('|', '\\|', acad_doc_title($page)) . ' | ' . (empty($page['noindex']) ? 'yes' : 'noindex') . " |\n";
}
$md .= "\n## 301 redirects\n\n| From | To |\n|---|---|\n";
foreach (acad_redirects() as $from => $to) {
    $md .= '| `' . $from . '` | `' . $to . "` |\n";
}
file_put_contents(ACAD_ROOT . '/docs/URL_INVENTORY.md', $md);

printf("Stubs written: %d, orphans removed: %d, pages: %d, redirects: %d, sitemap URLs: %d\n",
    $written, $removed, count(array_filter($targets, fn($k) => $k === 'page')), count(acad_redirects()), $count);
